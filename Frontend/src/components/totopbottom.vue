<script>
export default {
  name: "totopbottom",
  data() {
    return {
      show_left_button: false,
      show_right_button: false,
    };
  },
  methods: {
    scrollToTop() {
      window.scrollTo({
        top: 0,
        behavior: "smooth",
      });
    },
    scrollToBottom() {
      window.scrollTo({
        top:
          document.documentElement.scrollHeight || document.body.scrollHeight,
        behavior: "smooth",
      });
    },
    changeView() {
      let scroll_top =
        document.documentElement.scrollTop || document.body.scrollTop;
      let window_height =
        document.documentElement.clientHeight || document.body.clientHeight;
      let scroll_height =
        document.documentElement.scrollHeight || document.body.scrollHeight;
      this.show_left_button = scroll_height >= scroll_top + window_height + 360;
      this.show_right_button = window.scrollY > 360;
    },
    handleScroll() {
      this.changeView();
      this.$nextTick(() => {
        setTimeout(() => {
          this.changeView();
        }, 888);
      });
    },
  },
  mounted() {
    window.addEventListener("scroll", this.handleScroll);
  },
  beforeDestroy() {
    window.removeEventListener("scroll", this.handleScroll);
  },
};
</script>

